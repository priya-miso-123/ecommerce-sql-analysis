	3. Joined the cleaned category translation table (public.product_category_name_translation_cleaned) to retrieve category names in English.
	4. Grouped the records by product_id and product category.
	5. Counted the number of order item records for each product to calculate the total units sold.
	6. Calculated the total product sales value using the price column.
	7. Calculated the total freight charges using the freight_value column.
	8. Added product sales value and freight charges to calculate the total order value.
	9. Sorted the products by units sold in descending order and retrieved the top 10 products, including ties.
	
2. Top 10 Products by Sales Value:
	1. Used the cleaned order items view (public.olist_order_items_cleaned) as the main table.
	2. Joined the cleaned products table (public.olist_products_cleaned) using product_id to retrieve product category information.
	3. Joined the cleaned category translation table (public.product_category_name_translation_cleaned) to retrieve category names in English.
