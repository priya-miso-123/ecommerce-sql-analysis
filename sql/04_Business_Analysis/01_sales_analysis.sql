/*
=================================================
BUSINESS QUESTION:
What is the monthly and yearly revenue?

OBJECTIVE:
To calculate the monthly and yearly revenue generated by the shop using product prices and freight charges from delivered orders.

METHODOLOGY:
1. Monthly Revenue:
	1. Used the orders table as the main table to retrieve order purchase dates and order statuses.
	2. Joined the cleaned order items view (public.olist_order_items_cleaned) with the orders table using order_id.
	3. Filtered the records to include only delivered orders.
	4. Extracted the purchase month and year from order_purchase_timestamp to group the revenue by month.
	5. Added the product prices (price) and freight charges (freight_value) to calculate the total revenue for each month.
	6. Grouped the results by month and year and sorted them chronologically.
	
2. Yearly Revenue:
	1. Used the orders table as the main table to retrieve order purchase dates.
	2. Joined the cleaned order items view (public.olist_order_items_cleaned) with the orders table using order_id.
	3. Extracted the purchase year from order_purchase_timestamp.
	4. Added the product prices and freight charges to calculate the total revenue for each year.
	5. Grouped the results by year and sorted them chronologically.
=================================================
*/
-- Monthly Revenue
select 
	to_char(date_trunc('month',t1.order_purchase_timestamp),'YYYY-MM') as "Month",
	round(sum(t2.price+t2.freight_value)::numeric,2) as "Monthly Revenue"
from olist_orders_dataset as t1
inner join public.olist_order_items_cleaned as t2
	on t1.order_id = t2.order_id
where t1.order_status = 'delivered'
group by 
	"Month",
	date_trunc('year', t1.order_purchase_timestamp)
order by 
	"Month" ASC;

--Yearly Revenue

select 
	TO_CHAR(DATE_TRUNC('year',t1.order_purchase_timestamp),'YYYY') as "Year",
	round(sum((t2.price + t2.freight_value)::numeric),2) as "Yearly Payment Value"
from olist_orders_dataset as t1
inner join public.olist_order_items_cleaned as t2
	on t1.order_id = t2.order_id
where t1.order_status = 'delivered'
group by "Year"
order by "Year" ASC;

/*
=================================================
BUSINESS QUESTION:
Which product categories have the highest total order value, including freight charges?

OBJECTIVE:
To identify the product categories generating the highest total order value, including product sales and freight charges, and determine the highest revenue-generating category.

METHODOLOGY:
1. Used the cleaned order items view (public.olist_order_items_cleaned) as the main table for the analysis.
2. Joined the cleaned products table (public.olist_products_cleaned) using product_id to retrieve the product category associated with each order item.
3. Joined the cleaned category translation table (public.product_category_name_translation_cleaned) to retrieve the product category names in English.
4. Counted the order item records to calculate the total number of ordered items in each category.
5. Calculated the total product sales value using the price column.
6. Calculated the total freight charges using the freight_value column.
7. Added product sales value and freight charges to calculate the total order value for each category.
8. Grouped the results by English product category name.
9. Sorted the categories by total order value in descending order and retrieved the category or categories with the highest total order value using FETCH FIRST 1 ROW WITH TIES.

NOTE:
Used price and freight_value from the order items table instead of payment_value from the payments table to avoid counting the same order payment multiple times when an order contains multiple items.

=================================================
*/

SELECT
    t3.product_category_name_english AS product_category,
	count(t1.order_id) as total_order_items,
    ROUND(SUM(t1.price::numeric), 2) AS total_product_sales_value,
    ROUND(SUM(t1.freight_value::numeric), 2) AS total_freight_charges,
    ROUND(SUM(t1.price::numeric + t1.freight_value::numeric), 2) AS total_order_value
FROM public.olist_order_items_cleaned AS t1
LEFT JOIN public.olist_products_cleaned AS t2
    ON t1.product_id = t2.product_id
LEFT JOIN public.product_category_name_translation_cleaned AS t3
    ON t2.product_category_name = t3.product_category_name
GROUP BY t3.product_category_name_english
ORDER BY 
	total_order_value DESC
FETCH FIRST 1 ROW WITH TIES;

