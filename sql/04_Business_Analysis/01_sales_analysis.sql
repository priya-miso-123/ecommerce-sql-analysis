/*
=================================================
BUSINESS QUESTION:
What is the average order value (AOV)?

OBJECTIVE:

To calculate the Average Order Value (AOV) using two approaches:
	1. Payment-based AOV: Average amount paid by customers per order.
	2. Revenue-based AOV: Average product sales value, including freight charges, per order.

METHODOLOGY:

1. Payment-based AOV:
	1. Used the cleaned order payments table (public.olist_order_payments_cleaned) as the main table.
	2. Added all payment values to calculate the total amount paid by customers.
	3. Counted the distinct order IDs to calculate the total number of orders.
	4. Divided the total payment value by the total number of distinct orders to calculate the payment-based AOV.
	5. Rounded the result to two decimal places.

2. Revenue-based AOV:
	1. Used the cleaned order items view (public.olist_order_items_cleaned) as the main table.
	2. Added the product prices and freight charges to calculate the total product sales value, including freight.
	3. Counted the distinct order IDs to calculate the total number of orders.
	4. Divided the total product sales value, including freight, by the total number of distinct orders to calculate the revenue-based AOV.
	5. Rounded the result to two decimal places.

NOTE:

Used COUNT(DISTINCT order_id) because an order can contain multiple order items or multiple payment records.
The payment-based AOV uses actual payment records, whereas the revenue-based AOV uses product prices and freight charges from the order items table.

=================================================
*/

--Payment-based AOV: Total payment value / number of orders.

select 
	round(
		(sum(payment_value::numeric))/(count(distinct order_id)),2
	) as "Payment-based Average Order Value (AOV)"
from public.olist_order_payments_cleaned;

--Revenue-based AOV: Total product sales value (or product sales plus freight) / number of orders.

select
	round(
		sum(( price + freight_value)::numeric)/(count(distinct order_id)), 2
	) as "Revenue-based Average Order Value (AOV)"
from public.olist_order_items_cleaned;

/*
=================================================
BUSINESS QUESTION:
Which months have the highest order volume?

OBJECTIVE:

To identify the months with the highest order volume and evaluate their corresponding monthly sales value and Average Order Value (AOV).

METHODOLOGY:

1. Used the orders table (olist_orders_dataset) as the main table to retrieve order purchase dates and order IDs.
2. Joined the cleaned order payments table (public.olist_order_payments_cleaned) using order_id to retrieve payment details for each order.
3. Extracted the purchase month and year from order_purchase_timestamp to group the records by month and year.
4. Counted the distinct order IDs to calculate the monthly order volume.
5. Added the payment values to calculate the monthly sales value.
6. Divided the monthly sales value by the monthly order volume to calculate the monthly Average Order Value (AOV).
7. Sorted the results by monthly order volume in descending order, followed by purchase date in descending order.
8. Retrieved the top 10 months with the highest order volume using FETCH FIRST 10 ROWS WITH TIES.

NOTE:

Used COUNT(DISTINCT order_id) because an order can have multiple payment records.
Monthly sales value is calculated using payment_value from the payments table, which represents customer payment amounts rather than just product prices.
=================================================
*/

select 
	TO_CHAR(date_trunc('month',t1.order_purchase_timestamp),'Mon YYYY') as "Month-Year",
	count(distinct t1.order_id) as "Monthly Order Volume",
	round(sum(t2.payment_value::numeric),2) as "Monthly Sales Value",
	round(
		sum(t2.payment_value::numeric)/
		count(distinct t1.order_id),
		2
	) as "Monthly AOV"
from olist_orders_dataset as t1
left join public.olist_order_payments_cleaned as t2
on t1.order_id = t2.order_id
group by date_trunc('month',t1.order_purchase_timestamp)
order by 
	"Monthly Order Volume" DESC,
	date_trunc('month',t1.order_purchase_timestamp) DESC
fetch first 10 rows with ties;